"""Draw Bongo Cat frames for a 1-bit OLED and emit LVGL image descriptors.

Shapes are drawn at SS x scale with PIL and downsampled with a threshold, which
gives clean 1px outlines. Needs Pillow. From the repo root:

    python3 tools/bongo_cat.py boards/shields/dongle_display/widgets/bongo_cat_images.c [preview.png]
"""
import sys
from PIL import Image, ImageChops, ImageDraw, ImageFilter

W, H = 64, 36   # sprite size on the display
SS = 8          # supersampling factor
LW = SS         # 1px line at display scale

def S(*pts):
    return [v * SS for v in pts]

def desk_y(x):
    # Desk edge runs diagonally from the left down to the right
    return 25 + (x / W) * 9

def outlined(mask):
    """1px outline of a filled supersampled mask."""
    return ImageChops.subtract(mask, mask.filter(ImageFilter.MinFilter(LW * 2 + 1)))

def blob(shapes):
    m = Image.new('L', (W * SS, H * SS), 0)
    d = ImageDraw.Draw(m)
    for kind, pts in shapes:
        getattr(d, kind)(S(*pts), fill=255)
    return m

def above_desk(lift=0):
    m = Image.new('L', (W * SS, H * SS), 0)
    ImageDraw.Draw(m).polygon(S(0, 0, W, 0, W, desk_y(W) - lift, 0, desk_y(0) - lift), fill=255)
    return m

BODY = [('ellipse', (14, 2, 64, 50)),            # head/body blob, cut off by the desk
        ('polygon', (17, 15, 20, 2, 29, 8)),     # left ear
        ('polygon', (40, 5, 48, 0, 50, 12))]     # right ear

LEFT_PAW, RIGHT_PAW = 21, 39

def px(draw, x, y, w=1, h=1):
    """Pixel-exact filled rectangle in display coordinates."""
    draw.rectangle((x * SS, y * SS, (x + w) * SS - 1, (y + h) * SS - 1), fill=255)

def paw(canvas, cx, top, w, h, toes=False, impact=False):
    d = ImageDraw.Draw(canvas)
    box = S(cx - w / 2, top, cx + w / 2, top + h)
    d.ellipse(box, fill=0)
    d.ellipse(box, outline=255, width=LW)
    if toes:
        ty = round(top + h / 2) - 1
        px(d, round(cx) - 2, ty)
        px(d, round(cx) + 1, ty)
    if impact:
        # motion lines fanning up from both sides of the paw
        for side in (-1, 1):
            x = cx + side * (w / 2 + 1)
            d.line(S(x, top, x + side * 3, top - 3), fill=255, width=LW)
            d.line(S(cx + side * 2, top - 2, cx + side * 3, top - 5), fill=255, width=LW)

def frame(left, right, eyes='open'):
    canvas = Image.new('L', (W * SS, H * SS), 0)
    d = ImageDraw.Draw(canvas)
    d.line(S(0, desk_y(0), W, desk_y(W)), fill=255, width=LW)                  # desk
    body = ImageChops.multiply(blob(BODY), above_desk())
    canvas = ImageChops.lighter(canvas, outlined(body))
    d = ImageDraw.Draw(canvas)
    # eyes
    if eyes == 'open':
        px(d, 24, 13, 2, 2)
        px(d, 34, 12, 2, 2)
    elif eyes == 'closed':
        px(d, 23, 14, 3, 1)
        px(d, 33, 13, 3, 1)
    else:  # happy ^ ^
        px(d, 23, 14); px(d, 24, 13); px(d, 25, 14)
        px(d, 33, 13); px(d, 34, 12); px(d, 35, 13)
    # mouth (w)
    for x, y in [(28, 15), (29, 16), (30, 15), (31, 16), (32, 15)]:
        px(d, x, y)
    # paws
    for cx, state in ((LEFT_PAW, left), (RIGHT_PAW, right)):
        dy = desk_y(cx)
        if state == 'up':
            paw(canvas, cx, dy - 12, 9, 7, toes=True)
        elif state == 'down':
            paw(canvas, cx, dy - 4, 11, 4, impact=True)
        else:  # rest
            paw(canvas, cx, dy - 4.5, 10, 4.5)
    small = canvas.resize((W, H), Image.BOX)
    return small.point(lambda v: 255 if v > 80 else 0)

FRAMES = {
    'rest':       frame('rest', 'rest', 'open'),
    'rest_blink': frame('rest', 'rest', 'closed'),
    'up':         frame('up', 'up', 'open'),
    'left':       frame('down', 'up', 'happy'),
    'right':      frame('up', 'down', 'happy'),
    'both':       frame('down', 'down', 'happy'),
}

def to_c(name, img):
    stride = (W + 7) // 8
    data = []
    for y in range(H):
        row = [0] * stride
        for x in range(W):
            if img.getpixel((x, y)):
                row[x // 8] |= 0x80 >> (x % 8)
        data += row
    lines = [', '.join(f'0x{b:02x}' for b in data[i:i + stride]) + ',' for i in range(0, len(data), stride)]
    body = '\n  '.join(lines)
    return f'''static const LV_ATTRIBUTE_MEM_ALIGN uint8_t bongo_cat_{name}_map[] = {{
  0xff, 0xff, 0xff, 0xff, /* color of index 0: background */
  0x00, 0x00, 0x00, 0xff, /* color of index 1: lines (lit, the OLED runs with inversion-on) */
  {body}
}};

const lv_img_dsc_t bongo_cat_{name} = {{
  .header.cf = LV_IMG_CF_INDEXED_1BIT,
  .header.always_zero = 0,
  .header.reserved = 0,
  .header.w = {W},
  .header.h = {H},
  .data_size = {8 + len(data)},
  .data = bongo_cat_{name}_map,
}};
'''

if __name__ == '__main__':
    out_c = sys.argv[1]
    out_png = sys.argv[2] if len(sys.argv) > 2 else None
    with open(out_c, 'w') as f:
        f.write('/*\n * Generated by tools/bongo_cat.py - do not edit by hand.\n *\n * SPDX-License-Identifier: MIT\n */\n\n#include <lvgl.h>\n\n')
        f.write('#ifndef LV_ATTRIBUTE_MEM_ALIGN\n#define LV_ATTRIBUTE_MEM_ALIGN\n#endif\n\n')
        for name, img in FRAMES.items():
            f.write(to_c(name, img) + '\n')
    if not out_png:
        sys.exit(0)
    sc = 6
    sheet = Image.new('L', ((W * sc + 8) * 3, (H * sc + 8) * 2), 90)
    for i, img in enumerate(FRAMES.values()):
        sheet.paste(img.resize((W * sc, H * sc), Image.NEAREST), ((i % 3) * (W * sc + 8), (i // 3) * (H * sc + 8)))
    sheet.save(out_png)
